"""
build_top2_h5.py

Create a new HDF5 file like the previous one, except:
- It stores ONLY the top-2 modes and weights, generated by your CNN.
- The parameters' index 1 (0-based) is fixed to a constant for every waveguide.

If no model is provided, you can fallback to copying the first two columns from
existing 'modes' and 'weights' datasets.

Usage examples:
---------------
# Using a model (recommended)
python build_top2_h5.py \
  --in_h5 train_test_split.h5 \
  --out_h5 train_top2_pred.h5 \
  --model_module my_models.net4 \
  --model_class Net4_Top2 \
  --checkpoint path/to/model.pth \
  --fixed_param1 0.400 \
  --batch_size 512

# Fallback to existing datasets (no model)
python build_top2_h5.py \
  --in_h5 train_test_split.h5 \
  --out_h5 train_top2_pred.h5 \
  --fixed_param1 0.400 \
  --fallback_from_existing

Notes:
------
- Model must accept tensors: waveguide [B,1,H,W] (or [B,H,W], we will expand)
  and params [B,P], and return either:
    * [B,4]: (mode0, mode1, weight0, weight1), or
    * [B,2]: (mode0, weight0). If you also pass --two_pass with --second_head
      we call the model twice with a head selector kwarg to produce the two pairs.
- No normalization is applied unless you add it (see TODO hooks).
- Attributes about provenance are saved under /meta attrs in the output file.
"""

